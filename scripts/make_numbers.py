#!/usr/bin/env python3
"""Recompute every number of the computational section and write it as LaTeX.

Outputs (in generated/):
  numbers.tex      one \\newcommand per number, so the paper never retypes a value
  table_drift.tex  the drift table (a complete tabular environment)
  numbers.json     the same data, machine readable

Run:  python scripts/make_numbers.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from math import log

from sympy import legendre_symbol, nextprime

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from kxn import stats  # noqa: E402

OUT = ROOT / "generated"
SCALES = [3, 4, 5, 6, 9, 12, 15, 18, 21, 24, 27, 30]  # windows start at 10^j
PRIMES_PER_WINDOW = 250
REGIME_WINDOW = (10**5, 102_500)
DENSITY_WINDOW = (10**5, 10**5 + 3000)


def first_primes_above(lo: int, count: int):
    out, p = [], lo
    while len(out) < count:
        p = int(nextprime(p))
        out.append(p)
    return out


def compute() -> dict:
    data: dict = {"drift": [], "primes_per_window": PRIMES_PER_WINDOW}

    # --- n = 2: drift of the exact distribution with the size of p
    for j in SCALES:
        primes = first_primes_above(10**j, PRIMES_PER_WINDOW)
        d = stats.pooled(primes, 2, lambda p: 0)
        m = stats.moments(d)
        # mean of log(p / L_p): the same data on the unnormalized scale
        deficit = 0.0
        for p in primes:
            xs, ws = stats.x_distribution(p, 2, 0)
            deficit += float(((1.0 - xs) * ws).sum()) * log(p) / len(primes)
        data["drift"].append(
            {
                "exp": j,
                "last_prime": primes[-1],
                **m,
                "deficit": deficit,
                "p_above_09": stats.tail(d, lo=0.9),
                "correction": stats.correction_term(10.0**j),
            }
        )

    # --- n = 2: one window in detail
    primes = stats.window(*DENSITY_WINDOW)
    d = stats.pooled(primes, 2, lambda p: 0)
    data["density"] = {
        "primes": len(primes),
        **stats.moments(d),
        "p_above_09": stats.tail(d, lo=0.9),
        "p_below_05": stats.tail(d, hi=0.5),
    }

    # --- n = 3: the two regimes on the SAME primes
    primes = stats.window(*REGIME_WINDOW)
    fp = stats.pooled(primes, 3, lambda p: 0)
    fpf = stats.pooled(primes, 3, lambda p: 1)
    gaps, bounds = [], []
    for p in primes:
        a = stats.moments(stats.x_distribution(p, 3, 0))["mean"]
        b = stats.moments(stats.x_distribution(p, 3, 1))["mean"]
        gaps.append(b - a)
        bounds.append(stats.coupling_bound(p, 3))
    data["regime"] = {
        "primes": len(primes),
        "fp": stats.moments(fp),
        "fpf": stats.moments(fpf),
        "ks": stats.ks_distance(fp, fpf),
        "gap_mean": sum(gaps) / len(gaps),
        "gap_max": max(gaps),
        "bound_mean": sum(bounds) / len(bounds),
        "gaps_within_bound": all(-1e-12 <= g <= b + 1e-12 for g, b in zip(gaps, bounds)),
    }

    # --- n = 3, fixed k = 3: the split by regime also splits the primes
    qr = [p for p in primes if legendre_symbol(3, p) == 1]
    nr = [p for p in primes if legendre_symbol(3, p) == -1]
    shift = stats.qr_shift(3)
    a = stats.pooled(qr, 3, shift)
    b = stats.pooled(nr, 3, shift)
    perm = stats.label_permutation_test(qr, nr, 3, shift, trials=2000, seed=7)
    data["fixed_k"] = {
        "qr_primes": len(qr),
        "nr_primes": len(nr),
        "fp": stats.moments(a),
        "fpf": stats.moments(b),
        "ks": perm["observed"],
        "null_median": perm["null_median"],
        "null_95": perm["null_95"],
        "p_value": perm["p_value"],
        "same_regime_ks": stats.ks_distance(
            stats.pooled(qr, 3, lambda p: 0), stats.pooled(nr, 3, lambda p: 0)
        ),
    }
    return data


def macro(name: str, value) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def write(data: dict) -> None:
    OUT.mkdir(exist_ok=True)
    (OUT / "numbers.json").write_text(json.dumps(data, indent=2) + "\n")

    f4 = lambda x: f"{x:.4f}"
    f3 = lambda x: f"{x:.3f}"
    de, rg, fk = data["density"], data["regime"], data["fixed_k"]
    lines = [
        "% Generated by scripts/make_numbers.py. Do not edit by hand.",
        macro("NumWindowPrimes", data["primes_per_window"]),
        macro("NumDensPrimes", de["primes"]),
        macro("NumDensMean", f4(de["mean"])),
        macro("NumDensMedian", f4(de["median"])),
        macro("NumDensSd", f3(de["sd"])),
        macro("NumDensHigh", f3(de["p_above_09"])),
        macro("NumDensLow", f3(de["p_below_05"])),
        macro("NumRegPrimes", rg["primes"]),
        macro("NumRegMeanFP", f4(rg["fp"]["mean"])),
        macro("NumRegMeanFPF", f4(rg["fpf"]["mean"])),
        macro("NumRegMedFP", f4(rg["fp"]["median"])),
        macro("NumRegMedFPF", f4(rg["fpf"]["median"])),
        macro("NumRegKS", f3(rg["ks"])),
        macro("NumRegGapMean", f4(rg["gap_mean"])),
        macro("NumRegGapMax", f4(rg["gap_max"])),
        macro("NumRegBoundMean", f4(rg["bound_mean"])),
        macro("NumFixedQR", fk["qr_primes"]),
        macro("NumFixedNR", fk["nr_primes"]),
        macro("NumFixedKS", f3(fk["ks"])),
        macro("NumFixedNullMedian", f3(fk["null_median"])),
        macro("NumFixedNullTop", f3(fk["null_95"])),
        macro("NumFixedPval", f"{fk['p_value']:.2f}"),
        macro("NumFixedSameRegimeKS", f3(fk["same_regime_ks"])),
    ]
    (OUT / "numbers.tex").write_text("\n".join(lines) + "\n")

    rows = [
        f"$10^{{{r['exp']}}}$ & ${f4(r['mean'])}$ & ${f4(r['median'])}$ & ${f3(r['sd'])}$ & "
        f"${f3(r['p_above_09'])}$ & ${r['deficit']:.2f}$ & ${f3(r['correction'])}$\\\\"
        for r in data["drift"]
    ]
    head = (
        "\\begin{tabular}{lcccccc}\n\\toprule\n"
        "$p$ near & mean of $X_p$ & median & std.\\ dev. & $\\mathbb{P}[X_p > 0.9]$ & "
        "mean of $\\log(p/L_p)$ & $r(p)$\\\\\n\\midrule\n"
    )
    (OUT / "table_drift.tex").write_text(
        "% Generated by scripts/make_numbers.py. Do not edit by hand.\n"
        + head + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n"
    )


if __name__ == "__main__":
    result = compute()
    write(result)
    print(json.dumps(result, indent=2))
